namespace ZTX.HingesPistonsDocking
{
    internal static class DetMath
    {
        public static double Sin(double value) => Halfling.Mathx.Sin(value);

        public static double Cos(double value) => Halfling.Mathx.Cos(value);

        public static double Atan2(double y, double x) => Halfling.Mathx.Atan2(y, x);
    }
